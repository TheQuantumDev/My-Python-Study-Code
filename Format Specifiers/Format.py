price1 = 3.141482
price2 = 911.12
price3 = 32.44
price4 = 500.666
price5 = -700.91
price6 = 800.44
price7 = 444.444
price8 = 1000000

# Decimal point precision
print(f"Price1 is {price1:.2f}")

# Space addition 
print(f"Price2 is {price2:10}")

# Zero padding
print(f"Price3 is {price3:010}")

# Left justify
print(f"Price4 is {price4:<10}")

# Right justify
print(f"Price5 is {price5:>10}")

# Center align
print(f"Price6 is {price6:^10}")

# Precede plus to positive
print(f"Price7 is {price7:+}")

# Thousand separator
print(f"Price8 is {price8:,}")